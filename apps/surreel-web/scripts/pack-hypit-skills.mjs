#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "..");
const root = join(app, "..", "..");
const playbooks = join(root, "skills", "hypit", "references", "playbooks");
const formats = JSON.parse(readFileSync(join(app, "worker", "format-skills.json"), "utf8"));

function read(path) {
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n").trim();
}

function plannerCard(markdown, limit) {
  const keep = [];
  let afterHeading = 0;
  for (const line of markdown.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (/^#{1,3} /.test(trimmed)) {
      keep.push(trimmed.replace(/\[([^\]]+)\]\([^)]+\)/g, "$1"));
      afterHeading = 2;
      continue;
    }
    const useful =
      afterHeading > 0 ||
      /^[-*] |\d+\. |^>/.test(trimmed) ||
      /\b(must|never|always|required|do not|don't|cannot|keep|cast|spoken|caption|idle|lens|handheld)\b/i.test(
        trimmed,
      );
    if (!useful) continue;
    keep.push(trimmed.replace(/\[([^\]]+)\]\([^)]+\)/g, "$1"));
    if (afterHeading > 0) afterHeading -= 1;
  }
  let text = keep.join("\n");
  if (text.length > limit) text = text.slice(0, limit).replace(/\s+\S*$/, "").trim();
  return text;
}

const crafts = new Map();
const pack = {};
for (const format of formats) {
  const playbook = read(join(playbooks, "formats", format.playbook));
  const plannerCrafts = {};
  for (const craft of format.crafts) {
    if (!crafts.has(craft)) crafts.set(craft, read(join(playbooks, "craft", `${craft}.md`)));
    plannerCrafts[craft] = plannerCard(crafts.get(craft), 1600);
  }
  pack[format.id] = {
    id: format.id,
    title: format.title,
    playbook: `references/playbooks/formats/${format.playbook}`,
    crafts: format.crafts,
    plannerPlaybook: plannerCard(playbook, 2800),
    plannerCrafts,
  };
}

const out = join(app, "worker", "hypit-pack.ts");
writeFileSync(
  out,
  `/* Generated by scripts/pack-hypit-skills.mjs. Do not edit. */\nexport const hypitPack = ${JSON.stringify(pack, null, 2)} as const;\n`,
);
const bytes = Buffer.byteLength(readFileSync(out));
console.info(`Packed ${formats.length} formats, ${crafts.size} crafts → worker/hypit-pack.ts (${bytes} bytes)`);
